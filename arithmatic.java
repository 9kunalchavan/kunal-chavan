package java1;

public class arithmatic {
	public static void main(String[] args) {
		int a=10;
		int b=4;
		
		int sum =a+b;
		System.out.println("(a+b)"+sum);
		
		int sub =a-b;
		System.out.println("(a-b)"+sub);
		
		int multiply=a*b;
		System.out.println("(a*b)"+multiply);
		
		int divide=a/b;
		System.out.println("(a/b)"+divide);
	}

}
